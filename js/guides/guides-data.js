export function searchGuides(query, categoryFilter = 'all') {
  const q = query.trim().toLowerCase();
  return GUIDE_ITEMS.filter((entry) => {
    if (categoryFilter !== 'all' && entry.category !== categoryFilter) return false;
    if (!q) return true;
    return entry.searchText.includes(q) || fuzzyTokenMatch(entry.searchText, q);
  });
}

/** Простое совпадение по словам запроса */
function fuzzyTokenMatch(text, query) {
  const tokens = query.split(/\s+/).filter(Boolean);
  return tokens.every((t) => text.includes(t));
}
